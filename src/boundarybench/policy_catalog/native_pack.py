"""Generator for the ``boundary-native`` catalog pack.

The pack is a MECHANICAL projection of the native N×F×P single source of truth
(``daytona/policy_axes.py``): one policy per shipped preset that carries native
enforcement, one runtime variant, and one rule per emitted surface. Every rule's
``runtime_mappings`` come straight from ``runtime_mappings_for_preset`` and its
``source_refs`` from that surface's axis NIST citations, so the pack can never
drift from the config generator — the committed ``pack.yaml`` is regenerated by
this function and guarded by ``tests/test_boundary_native_pack.py``.

``control`` (n0-f0-p0) is excluded: it makes no native enforcement claim, so it
has no mappings and therefore no rule to author.

Regenerate the committed YAML with::

    python -m boundarybench.policy_catalog.native_pack
"""

from __future__ import annotations

from pathlib import Path

import yaml

from boundarybench.daytona.policy_axes import (
    AXIS_PRESETS,
    AxisPreset,
    RuntimeMapping as AxisRuntimeMapping,
    runtime_mappings_for_preset,
)
from boundarybench.policy_catalog.catalog.loader import catalog_packs_root
from boundarybench.policy_catalog.catalog.schema import (
    CATALOG_SCHEMA_VERSION,
    COMPILER_CONTRACT_VERSION,
    DAYTONA_HARDENING_V1,
    FidelityLevel,
    MappingStatus,
    PolicyDefinition,
    PolicyPack,
    PolicyRule,
    PolicyVariant,
    RuntimeMapping,
    RuntimeTargetBinding,
    SourceProvenance,
    SourceReference,
)

NATIVE_PACK_ID = "boundary-native"
NATIVE_PACK_VERSION = "1.0.0"
_SOURCE_FRAMEWORK = "native/boundary"
_NIST_FRAMEWORK = "NIST SP 800-53 Rev. 5"
_SOURCE_PATH = "src/boundarybench/daytona/policy_axes.py"


