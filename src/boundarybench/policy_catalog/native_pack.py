def native_variant_id(preset_name: str) -> str:
    """The single runtime variant id for a preset's native policy."""
    return f"{preset_name}-daytona-v1"


def _rule_for_mapping(preset: AxisPreset, mapping: AxisRuntimeMapping) -> PolicyRule:
    title, intended_effect, verification_hint = _SURFACE_PROSE[mapping.surface]
    source_refs = tuple(
        SourceReference(framework=_NIST_FRAMEWORK, control_id=control_id)
        for control_id in mapping.nist_refs
    )
    return PolicyRule(
        rule_id=f"{preset.name}.{mapping.surface}",
        title=title,
        description=(
            f"{title} for the {preset.name} preset ({preset.tuple_id}), "
            f"enforced natively via daytona-hardening-v1."
        ),
        intended_effect=intended_effect,
        source_refs=source_refs,
        runtime_mappings=(
            RuntimeMapping(
                target=DAYTONA_HARDENING_V1,
                surface=mapping.surface,
                status=MappingStatus.ENFORCED,
                values=mapping.values,
                verification_hint=verification_hint,
            ),
        ),
    )


def _policy_for_preset(preset: AxisPreset) -> PolicyDefinition:
    mappings = runtime_mappings_for_preset(preset)
    rules = tuple(_rule_for_mapping(preset, mapping) for mapping in mappings)
    variant = PolicyVariant(
        variant_id=native_variant_id(preset.name),
        title=f"{preset.name} native enforcement ({preset.tuple_id})",
        description=preset.nist_story,
        fidelity=FidelityLevel.RUNTIME_ENFORCED_PARTIAL,
        runtime_targets=(
            RuntimeTargetBinding(
                target=DAYTONA_HARDENING_V1,
                capability_set=DAYTONA_HARDENING_V1,
                compiler_contract_version=COMPILER_CONTRACT_VERSION,
            ),
        ),
        rules=rules,
        metadata={
            "tuple_id": preset.tuple_id,
            "tier": preset.tier,
            "compile_status_counts": {"enforced": len(rules)},
        },
    )
    return PolicyDefinition(
        policy_id=preset.name,
        family="boundary-native-nxfxp",
        title=f"BoundaryBench native preset: {preset.name} ({preset.tuple_id})",
        description=preset.nist_story,
        variants=(variant,),
        metadata={"tuple_id": preset.tuple_id, "tier": preset.tier},
    )


def build_native_policy_pack() -> PolicyPack:
    """Build the ``boundary-native`` pack from the policy_axes source of truth."""
    policies = tuple(
        _policy_for_preset(preset)
        for preset in AXIS_PRESETS.values()
        if runtime_mappings_for_preset(preset)
    )
    excluded = tuple(
        name
        for name, preset in AXIS_PRESETS.items()
        if not runtime_mappings_for_preset(preset)
    )
    return PolicyPack(
        catalog_schema_version=CATALOG_SCHEMA_VERSION,
        pack_id=NATIVE_PACK_ID,
        title="BoundaryBench Native N×F×P Enforcement",
        version=NATIVE_PACK_VERSION,
        description=(
            "Native N×F×P enforcement claims for the shipped preset roster. "
            "Mechanically generated from daytona/policy_axes.py (AXIS_PRESETS + "
            "runtime_mappings_for_preset); see boundarybench.policy_catalog."
            "native_pack.build_native_policy_pack."
        ),
        source=SourceProvenance(
            framework=_SOURCE_FRAMEWORK,
            provenance_note=(
                "Generated from the native N×F×P single source of truth in "
                "daytona/policy_axes.py; not derived from an external framework "
                "corpus. NIST control ids are cited per surface as evidence anchors."
            ),
            source_paths=(_SOURCE_PATH,),
        ),
        policies=policies,
        metadata={
            "generator": (
                "boundarybench.policy_catalog.native_pack:build_native_policy_pack"
            ),
            "excluded_presets": list(excluded),
        },
    )


def render_native_pack_yaml() -> str:
    """Serialize the generated pack to the committed YAML text."""
    return yaml.safe_dump(
        build_native_policy_pack().to_dict(),
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
    )


def native_pack_path() -> Path:
    return catalog_packs_root() / NATIVE_PACK_ID / "pack.yaml"


def write_native_pack_yaml() -> Path:
    """Regenerate the committed ``pack.yaml`` on disk; returns its path."""
    path = native_pack_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_native_pack_yaml(), encoding="utf-8")
    return path


if __name__ == "__main__":  # pragma: no cover - regeneration entry point
    written = write_native_pack_yaml()
    print(f"wrote {written}")
